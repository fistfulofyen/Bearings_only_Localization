"""Make a flat, single-folder copy of the report for easy upload to Overleaf.

Usage (from the project root)::

    python report/flatten_for_overleaf.py

Writes

* ``report/overleaf/`` -- ``report.tex`` with every generated number and table
  written into it (no ``\\input`` of other files), plus all figures in the same
  folder (no sub-folders);
* ``report_overleaf.zip`` (project root) -- the same files, flat, ready for
  Overleaf's *New Project > Upload Project*.

Run it again after ``make_figures.py`` or after editing ``report.tex``.
"""

from __future__ import annotations

import re
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "report"
OUT = REPORT / "overleaf"
ZIP = ROOT / "report_overleaf.zip"


def flatten(tex: str) -> str:
    """Inline the generated results and tables into the report source."""
    gen = REPORT / "generated"
    results = (gen / "results.tex").read_text(encoding="utf-8").rstrip()
    line = r"\input{generated/results}   % numerical results written by make_figures.py"
    assert tex.count(line) == 1, "results \\input line not found"
    tex = tex.replace(line, "% ---- numerical results (generated by make_figures.py) ----\n" + results)

    helper = re.compile(r"% rows of a generated table.*?\\makeatother\n", re.S)
    assert len(helper.findall(tex)) == 1, "\\tablerows definition not found"
    tex = helper.sub("", tex)

    def rows(match: re.Match) -> str:
        return (gen / f"{match.group(1)}.tex").read_text(encoding="utf-8").rstrip()

    tex = re.sub(r"\\tablerows\{(\w+)\}", rows, tex)
    tex = tex.replace(r"\graphicspath{{figures/}}", r"\graphicspath{{./}{figures/}}")
    return tex


def check(tex: str, folder: Path) -> list[str]:
    """Problems that would stop the flat copy from compiling."""
    problems = []
    for cmd in (r"\input{", r"\tablerows", r"\include{"):
        if cmd in tex:
            problems.append(f"still contains {cmd}")
    for name in re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", tex):
        if not (folder / name).is_file():
            problems.append(f"missing figure {name}")
    defined = set(re.findall(r"\\newcommand\{\\(\w+)\}", tex))
    used = set(re.findall(r"\\([a-z][A-Za-z]+[A-Z][A-Za-z]*)", tex))
    problems += [f"undefined macro \\{m}" for m in sorted(used - defined)]
    return problems


def main() -> int:
    tex = flatten((REPORT / "report.tex").read_text(encoding="utf-8"))
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    (OUT / "report.tex").write_text(tex, encoding="utf-8")
    figures = sorted((REPORT / "figures").glob("*"))
    for f in figures:
        shutil.copy2(f, OUT / f.name)
    problems = check(tex, OUT)
    if problems:
        print("PROBLEMS:", *problems, sep="\n  ")
        return 1
    with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(OUT.iterdir()):
            z.write(f, f.name)          # flat: no folders inside the zip
    print(f"report/overleaf/: report.tex + {len(figures)} figures (single folder, no \\input)")
    print(f"{ZIP.name}: {ZIP.stat().st_size / 1e6:.1f} MB, {len(figures) + 1} files, no sub-folders")
    return 0


if __name__ == "__main__":
    sys.exit(main())
